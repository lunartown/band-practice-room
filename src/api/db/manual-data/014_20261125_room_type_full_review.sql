DELETE FROM room_type_assignments a
USING rooms r, studios s
WHERE a.room_id = r.id AND r.studio_id = s.id
  AND EXISTS (SELECT 1 FROM room_type_review v WHERE v.studio_slug = s.slug AND v.room_name = r.name)
  AND NOT EXISTS (
    SELECT 1 FROM room_type_review v JOIN room_types rt ON rt.slug = v.type_slug
    WHERE v.studio_slug = s.slug AND v.room_name = r.name AND rt.id = a.room_type_id
  );

UPDATE room_type_assignments a SET is_primary = false
FROM rooms r, studios s, room_types rt, room_type_review v
WHERE a.room_id = r.id AND r.studio_id = s.id AND a.room_type_id = rt.id
  AND v.studio_slug = s.slug AND v.room_name = r.name AND v.type_slug = rt.slug
  AND a.is_primary AND NOT v.is_primary;

INSERT INTO room_type_assignments (room_id, room_type_id, is_primary, source, note)
SELECT r.id, rt.id, v.is_primary, 'MANUAL', v.note
FROM room_type_review v
JOIN studios s ON s.slug = v.studio_slug
JOIN rooms r ON r.studio_id = s.id AND r.name = v.room_name
JOIN room_types rt ON rt.slug = v.type_slug
ON CONFLICT (room_id, room_type_id) DO UPDATE
SET is_primary = EXCLUDED.is_primary,
    source = EXCLUDED.source,
    note = EXCLUDED.note,
    updated_at = now();
